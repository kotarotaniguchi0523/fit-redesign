/**
 * `app/content/guide.mdx` を素の HTML 断片へ変換し、
 * `app/content/guide.generated.ts` として出力する。
 *
 * Remix へ移行後は MDX コンパイラを持たないため、ビルド時に Markdown ブロック
 * （見出し / リスト / 段落）とインライン記法（強調 / コード / リンク）を展開し、
 * 元から含まれる HTML（<strong> など）はそのまま通す。
 *
 * 使い方: node scripts/build-guide.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const source = readFileSync('app/content/guide.mdx', 'utf8')

function escapeHtml(value) {
	return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

function inline(text) {
	// 元から入っている HTML タグは保護し、Markdown のインライン記法だけ変換する
	const tokens = []
	const protectedText = text.replace(/<[^>]+>/g, (tag) => {
		tokens.push(tag)
		return `\u0000${tokens.length - 1}\u0000`
	})

	const converted = escapeHtml(protectedText)
		.replace(/`([^`]+)`/g, '<code>$1</code>')
		.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
		.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')

	return converted.replace(/\u0000(\d+)\u0000/g, (_match, index) => tokens[Number(index)])
}

const lines = source.split('\n')
const html = []
let listType = null

function closeList() {
	if (listType) {
		html.push(`</${listType}>`)
		listType = null
	}
}

for (const rawLine of lines) {
	const line = rawLine.trimEnd()
	if (line.trim() === '') {
		closeList()
		continue
	}
	const heading = line.match(/^(#{1,6})\s+(.*)$/)
	if (heading) {
		closeList()
		const level = heading[1].length
		html.push(`<h${level}>${inline(heading[2])}</h${level}>`)
		continue
	}
	const ordered = line.match(/^\d+\.\s+(.*)$/)
	if (ordered) {
		if (listType !== 'ol') {
			closeList()
			html.push('<ol>')
			listType = 'ol'
		}
		html.push(`<li>${inline(ordered[1])}</li>`)
		continue
	}
	const bullet = line.match(/^[-*]\s+(.*)$/)
	if (bullet) {
		if (listType !== 'ul') {
			closeList()
			html.push('<ul>')
			listType = 'ul'
		}
		html.push(`<li>${inline(bullet[1])}</li>`)
		continue
	}
	closeList()
	html.push(`<p>${inline(line)}</p>`)
}
closeList()

const output = `// Generated by scripts/build-guide.mjs. Do not edit by hand.
export const guideHtml = ${JSON.stringify(html.join('\n'))}
`

writeFileSync('app/content/guide.generated.ts', output)
console.log(`wrote app/content/guide.generated.ts (${html.length} blocks)`)
