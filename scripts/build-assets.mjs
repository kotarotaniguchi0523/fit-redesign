/**
 * ブラウザー資産のビルド（Remix 標準のアセットサーバーで生成）。
 *
 * Remix のアンバンドル配信では `remix/assets` がリクエスト時に TypeScript を
 * コンパイルし、import map と modulepreload を返す。Cloudflare Workers の実行時には
 * oxc のネイティブバインディングが動かないため、ここで同じアセットサーバーを
 * Node 上で回し、その出力（URL ごとのコンパイル結果）を `public/` へ書き出して
 * Workers Assets から配信する。
 *
 * 使い方: node scripts/build-assets.mjs
 */
import { readdirSync, readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import { init, parse } from "es-module-lexer";
import { createAssetServer } from "remix/assets";

import { CLIENT_ENTRY_HREF } from "../app/client-entry.ts";

/** ブラウザー入口（`run()` を呼ぶ薄いモジュール）。 */
const ENTRY_FILE = "app/actions/public/entry.ts";
const OUTPUT_DIR = "public";
const GENERATED_MODULE = "app/content/assets.generated.ts";
const ORIGIN = "http://asset.local";

const assetServer = createAssetServer({
	basePath: "/assets",
	rootDir: process.cwd(),
	allowFiles: ["app/**"],
	allowPackages: ["remix", "@remix-run/ui", "@remix-run/component", "neverthrow", "zod"],
	denyFiles: ["app/**/*.test.*"],
	watch: false,
});

/** URL のパスを `public/` 配下のファイルパスへ変換する（Workers Assets と同じ解決）。 */
function outputPathFor(urlPath) {
	return join(OUTPUT_DIR, decodeURIComponent(urlPath));
}

async function fetchAsset(urlPath) {
	const response = await assetServer.fetch(new Request(ORIGIN + urlPath));
	if (!response || response.status !== 200) {
		return null;
	}
	return response;
}

/** コンパイル済み JS が参照する同一生成物の URL を集める。 */
function collectImports(source, ownUrlPath) {
	const [imports] = parse(source);
	const urls = [];
	for (const statement of imports) {
		const specifier = statement.n;
		if (!specifier || specifier.startsWith("data:")) {
			continue;
		}
		const resolved = new URL(specifier, ORIGIN + ownUrlPath).pathname;
		if (resolved.startsWith("/assets/")) {
			urls.push(resolved);
		}
	}
	return urls;
}

/** 複数の `getScriptEntry()` 結果の import map をマージする。 */
function mergeImportMaps(entries) {
	const imports = {};
	const scopes = {};
	for (const item of entries) {
		const map = item.importMap ?? {};
		Object.assign(imports, map.imports ?? {});
		for (const [prefix, specifiers] of Object.entries(map.scopes ?? {})) {
			scopes[prefix] = { ...(scopes[prefix] ?? {}), ...specifiers };
		}
	}
	return { imports, scopes };
}

/** `clientEntry(` を含むファイルを島の入口として拾う。 */
function findClientEntryFiles() {
	const files = [];
	const walk = (directory) => {
		for (const entry of readdirSync(directory, { withFileTypes: true })) {
			const path = `${directory}/${entry.name}`;
			if (entry.isDirectory()) {
				walk(path);
			} else if (entry.name.endsWith(".tsx") && !entry.name.includes(".test.")) {
				if (readFileSync(path, "utf8").includes("clientEntry(")) {
					files.push(path);
				}
			}
		}
	};
	walk("app");
	return files.sort();
}

async function main() {
	await init;

	const entry = await assetServer.getScriptEntry(ENTRY_FILE);

	if (entry.href !== CLIENT_ENTRY_HREF) {
		throw new Error(
			`Client entry href changed: asset server says "${entry.href}" but app/client-entry.ts has "${CLIENT_ENTRY_HREF}". Update app/client-entry.ts.`,
		);
	}

	// 島（clientEntry）はそれぞれ自分のモジュールを入口にするため、
	// ルート入口からは到達しない。ソースから島を拾って探索と import map の対象にする。
	const islandEntries = await Promise.all(
		findClientEntryFiles().map((file) => assetServer.getScriptEntry(file)),
	);
	const rootHrefs = [
		entry.href,
		...entry.preloads,
		...islandEntries.flatMap((island) => [island.href, ...island.preloads]),
	];

	// 島はそれぞれ別の入口なので、ルート入口の import map だけでは足りない。
	// 全入口の import map をマージして、どの島の bare specifier も解決できるようにする。
	const importMap = mergeImportMaps([entry, ...islandEntries]);
	const manifest = {
		importMap,
		preloads: entry.preloads,
	};
	await writeFile(
		GENERATED_MODULE,
		`// Generated by scripts/build-assets.mjs. Do not edit by hand.\n` +
			`/** \`getScriptEntry()\` の import map と modulepreload（Document が描画する）。 */\n` +
			`export const scriptEntry = ${JSON.stringify(manifest, null, "\t")} as const;\n`,
	);

	const seen = new Set();
	const queue = rootHrefs;

	while (queue.length > 0) {
		const urlPath = queue.shift();
		if (seen.has(urlPath)) {
			continue;
		}
		seen.add(urlPath);

		const response = await fetchAsset(urlPath);
		if (!response) {
			continue;
		}
		const body = await response.text();
		const filePath = outputPathFor(urlPath);
		await mkdir(dirname(filePath), { recursive: true });
		await writeFile(filePath, body);

		const contentType = response.headers.get("content-type") ?? "";
		if (contentType.includes("javascript")) {
			queue.push(...collectImports(body, urlPath));
		}
	}

	console.log(`wrote ${seen.size} browser modules from ${entry.href}`);
	console.log(`wrote ${GENERATED_MODULE} (${manifest.preloads.length} preloads)`);
}

await main();
