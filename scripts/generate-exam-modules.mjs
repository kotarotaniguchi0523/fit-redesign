/**
 * `app/data/exams/modules.generated.ts` を生成する。
 *
 * Vite 固有の `import.meta.glob` は Remix のテストランナー（esbuild/node）では
 * 動かないため、`app/data/exams-json/exam{n}-{year}.json` を明示的に import する
 * 索引モジュールを生成する。JSON の import attributes は Node 24 / esbuild の
 * 双方で動く標準機能。
 *
 * 使い方: node scripts/generate-exam-modules.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs'

const JSON_DIR = 'app/data/exams-json'
const OUT_FILE = 'app/data/exams/modules.generated.ts'

const files = readdirSync(JSON_DIR)
	.filter((name) => /^exam\d+-\d{4}\.json$/.test(name))
	.sort((a, b) => {
		const [, examA, yearA] = a.match(/exam(\d+)-(\d{4})/)
		const [, examB, yearB] = b.match(/exam(\d+)-(\d{4})/)
		return Number(yearA) - Number(yearB) || Number(examA) - Number(examB)
	})

const identifier = (file) =>
	'exam' + file.replace(/^exam/, '').replace(/\.json$/, '').replace(/-/g, '_')

const lines = [
	'// Generated by scripts/generate-exam-modules.mjs. Do not edit by hand.',
	'// JSON を明示的に import する索引。Vite 固有の `import.meta.glob` を置き換える。',
	'',
	...files.map((file) => `import ${identifier(file)} from '../exams-json/${file}' with { type: 'json' }`),
	'',
	'/** import.meta.glob 相当: パス -> { default: JSON } のマップ */',
	'export const examModules: Record<string, { default: unknown }> = {',
	...files.map((file) => `\t'../exams-json/${file}': { default: ${identifier(file)} },`),
	'}',
	'',
]

writeFileSync(OUT_FILE, lines.join('\n'))
console.log(`wrote ${OUT_FILE} with ${files.length} modules`)
